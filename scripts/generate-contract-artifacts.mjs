import { readFileSync, writeFileSync } from "node:fs";
import { keccak256 } from "viem";

const forwarder = JSON.parse(
  readFileSync("contracts/out/PaymentForwarder.sol/PaymentForwarder.json", "utf8"),
);
const factory = JSON.parse(
  readFileSync("contracts/out/PaymentForwarderFactory.sol/PaymentForwarderFactory.json", "utf8"),
);
const output = `// Generated by npm run contracts:artifacts. Do not edit.
export const PAYMENT_FORWARDER_CREATION_CODE =
  "${forwarder.bytecode.object}" as const;
export const PAYMENT_FORWARDER_FACTORY_RUNTIME_CODE =
  "${factory.deployedBytecode.object}" as const;
export const PAYMENT_FORWARDER_FACTORY_RUNTIME_CODE_HASH =
  "${keccak256(factory.deployedBytecode.object)}" as const;
`;
const target = "src/contracts.generated.ts";

if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) {
    console.error(`${target} is stale; run npm run contracts:artifacts`);
    process.exit(1);
  }
} else {
  writeFileSync(target, output);
}
